	const int Volume = 16, Clamp = 27500;

	static int S16(long v) => (short)(ushort)(v & 0xFFFF);

	public record struct LpcFrame(int Energy, int Pitch, int[] K);

	sealed class Bits
	{
		readonly byte[] d; readonly int o; public long Pos;
		public Bits(byte[] data, int offset) { d = data; o = offset; }
		public int Get(int n)
		{
			int v = 0;
			for(int i = 0; i < n; i++) {
				long bi = o + (Pos >> 3);
				int b = bi < d.Length ? d[bi] : 0;
				v = v << 1 | (b >> (int)(Pos & 7) & 1);
				Pos++;
			}
			return v;
		}
	}

	/// <summary>The frames of a stream (bytes after the $D6 sync); stops at energy 15</summary>
	public static List<LpcFrame> Frames(byte[] phrase, int start = 3)
	{
		var b = new Bits(phrase, start);
		long totalBits = (long)(phrase.Length - start) * 8;
		var refK = new int[10];
		var o = new List<LpcFrame>();
		while(b.Pos < totalBits) {
			int e = b.Get(4);
			if(e == 0) { o.Add(new LpcFrame(0, 0, new int[10])); continue; }
			if(e == 15) break;
			int rep = b.Get(1), pi = b.Get(7);
			var k = (int[])refK.Clone();
			if(rep == 0) for(int i = 0; i < 4; i++) k[i] = K[i][b.Get(KBits[i])];
			if(pi == 0) for(int i = 4; i < 10; i++) k[i] = 0;
			else if(rep == 0) for(int i = 4; i < 10; i++) k[i] = K[i][b.Get(KBits[i])];
			refK = k;
			o.Add(new LpcFrame(Gain[e], Pitch[pi], k));
		}
		return o;
	}

	static bool InterpNeeded(LpcFrame p, LpcFrame n)
	{
		if(p.Energy == 0) return !(n.Pitch == 0 && n.Energy != 0);
		if(p.Pitch != 0) return !(n.Pitch == 0 && n.Energy != 0);
		return n.Pitch == 0;
	}

	/// <summary>phrase: length (BE16), $D6, stream -> 16-bit samples at 10 kHz</summary>
	public static List<int> Synth(byte[] phrase)
	{
		var fr = Frames(phrase);
		var o = new List<int>();
		if(fr.Count == 0) return o;
		var zero = new LpcFrame(0, 0, new int[10]);
		LpcFrame prev = fr[0], nxt = fr.Count > 1 ? fr[1] : zero;
		int idx = 2;
		int curE = prev.Energy, curP = prev.Pitch;
		var curK = (int[])prev.K.Clone();
		var x = new int[11];
		int curPitch = 0, seed = -1;
		bool need = InterpNeeded(prev, nxt);
		for(int f = 0; f < fr.Count + 1; f++) {
			for(int i = 0; i < 200; i++) {
				curPitch -= 16;
				if(curPitch < 0) {
					int cp = curPitch;
					bool done = false;
					if(need) {
						long ratio = ((long)i << 15) / 200;
						int[] pv = new[] { prev.Energy, prev.Pitch }.Concat(prev.K).ToArray();
						int[] nv = new[] { nxt.Energy, nxt.Pitch }.Concat(nxt.K).ToArray();
						var cv = new int[12];
						//the chip's frame fields are 16-bit: an interpolated coefficient that overflows
						//wraps (a reflection coefficient past +/-1 would make the filter blow up)
						for(int j = 0; j < 12; j++) cv[j] = S16(S16(S16(nv[j] - pv[j]) * ratio >> 15) + pv[j]);
						curE = cv[0]; curP = cv[1]; curK = cv[2..];
						cp += curP;
						if(cp > 0) { curPitch = cp; done = true; }
					}
					if(!done) curPitch = curP != 0 ? cp + curP : 0x80;
				}
				int ex;
				if(curP == 0) {
					if(curE != 0) {
						int s = S16((seed << 1) & 0xFFFF);
						int r = ((s >> 12) ^ (s >> 13)) & 1;
						seed = s | r;
						ex = ((r != 0 ? 1408 : -1408) * curE) >> 15;
					} else ex = 0;
				} else if(curPitch >= 160) ex = 0;
				else ex = (Excit[curPitch < 0 ? curPitch + Excit.Length : curPitch] * curE) >> 15;  // a negative index counts from the end
				long sample = S16((ex * Volume) >> 1);
				for(int j = 9; j >= 0; j--) {
					sample -= ((long)curK[j] * x[j]) >> 15;
					sample = Math.Max(-Clamp - 1, Math.Min(Clamp, sample));
					x[j + 1] = S16(x[j] + S16((sample * curK[j]) >> 15));
				}
				x[0] = S16(sample);
				o.Add(x[0]);
			}
			prev = nxt;
			curE = nxt.Energy; curP = nxt.Pitch; curK = (int[])nxt.K.Clone();
			nxt = idx < fr.Count ? fr[idx] : zero;
			idx++;
			need = InterpNeeded(prev, nxt);
		}
		return o;
	}

	public static void WriteWav(string path, IList<int> samples, int rate = 10000)
	{
		using var f = File.Create(path);
		using var w = new BinaryWriter(f);
		int n = samples.Count;
		w.Write("RIFF"u8.ToArray()); w.Write(36 + n * 2); w.Write("WAVE"u8.ToArray());
		w.Write("fmt "u8.ToArray()); w.Write(16); w.Write((short)1); w.Write((short)1); w.Write(rate); w.Write(rate * 2); w.Write((short)2); w.Write((short)16);
		w.Write("data"u8.ToArray()); w.Write(n * 2);
		foreach(var s in samples) w.Write((short)Math.Clamp(s, -32768, 32767));
	}
